export function styleAnalyzeMessages(samples) {
  const body = samples.map((s, i) => `【片段${i + 1}】\n${s}`).join('\n\n')
  return [
    { role: 'system', content: STYLE_SYSTEM },
    { role: 'user', content: `以下是这本小说的采样片段，请提炼写作习惯：\n\n${body}` },
  ]
}

