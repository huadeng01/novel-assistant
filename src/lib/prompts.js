const HABIT_SHORTEN_TAIL = '（纠偏：此处「短句节奏」指长句内部用小句切开、逗号密集，不是把全书写成一片短句；铺陈背景与心理仍保留原著本来的长句节奏）'
export function sanitizeHabits(habits) {
  const list = Array.isArray(habits) ? habits.filter((h) => typeof h === 'string' && h.trim()) : []
  const out = []
  let removed = 0
  let patched = 0
  let shortened = 0
  let requoted = 0
  for (const raw of list) {
    // L33 项3：否定式提及（「…不连成无标点字串」）不是「要求省标点」，豁免剔除，继续走下面三条既有判定。
    if (HABIT_DROP_RE.test(raw) && !HABIT_DROP_NEG_RE.test(raw)) {
      removed++
      continue
    }
    // 就地改写（不 continue）：改完的字面继续接受 SHORTEN/PATCH 判定
    let h = raw
    if (HABIT_QUOTE_RE.test(h)) {
      const fixed = h.replace(/直角引号/g, '中文双引号').replace(HABIT_QUOTE_PAIR_RE, (_m, inner) => `“${inner}”`)
      if (fixed !== h) {
        h = fixed
        requoted++
      }
    }
    if (HABIT_SHORTEN_RE.test(h) && !h.includes('纠偏')) {
      out.push(h + HABIT_SHORTEN_TAIL)
      shortened++
      continue
    }
    // M9：幂等判据同时认「顿号」与「逗号」——habit 已自带"以逗号分隔"时不再重补同义尾注（原只认顿号，会误伤 infinite 档案 habits[4]）
    if (HABIT_PATCH_RE.test(h) && !h.includes('顿号') && !h.includes('逗号')) {
      out.push(h + HABIT_PATCH_TAIL)
      patched++
      continue
    }
    out.push(h)
  }
  return { habits: out, removed, patched, shortened, requoted, flagged: removed > 0 || patched > 0 || shortened > 0 || requoted > 0 }
}

